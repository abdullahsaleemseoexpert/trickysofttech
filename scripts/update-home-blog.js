// Home page "From the Blog" section: the 6 newest posts (by datePublished), as plain crawlable links.
// Runs automatically in the deploy workflow (.github/workflows/deploy.yml) before the FTP upload, so a new post
// appears on the home page as soon as it is pushed. Can also be run locally:  node scripts/update-home-blog.js
const fs = require('fs');
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const N = 6;
const dec = s => s.replace(/&amp;/g, '&').replace(/&#39;/g, "'").replace(/&hellip;/g, '\u2026').replace(/&quot;/g, '"');
const esc = s => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];

const idx = fs.readFileSync(ROOT + '/blog/index.html', 'utf8').replace(/\r\n/g, '\n');
const posts = [];
for (const f of fs.readdirSync(ROOT + '/blog').filter(f => f.endsWith('.html') && f !== 'index.html')) {
  const slug = f.replace('.html', '');
  const h = fs.readFileSync(`${ROOT}/blog/${f}`, 'utf8');
  const date = (h.match(/"datePublished":"([0-9-]+)"/) || [])[1];
  if (!date) continue;
  const art = h.slice(h.indexOf('<article'), h.indexOf('</article>'));
  const words = art.replace(/<svg[\s\S]*?<\/svg>/g, ' ').replace(/<[^>]+>/g, ' ').split(/\s+/).filter(Boolean).length;
  const meta = dec((h.match(/<meta name="description" content="([^"]*)"/) || [])[1] || '');
  const h1 = dec((h.match(/<h1[^>]*>([^<]*)<\/h1>/) || [])[1] || '').trim();
  // the tidy name / label / blurb the blog index already uses for this post
  const ci = idx.indexOf(`href="${slug}" class="rel-card`);
  let name = h1, label = 'Local SEO', blurb = meta;
  if (ci >= 0) {
    const blk = idx.slice(ci, idx.indexOf('</a>', ci));
    name = dec((blk.match(/<div class="rel-name">([^<]*)<\/div>/) || [, name])[1]);
    label = dec((blk.match(/<div class="rel-label">([^<]*)<\/div>/) || [, label])[1]);
    const b = blk.match(/<div style="font-size:13\.5px[^>]*>([^<]*)<\/div>/);
    if (b) blurb = dec(b[1]);
  }
  if (blurb.length > 150) blurb = blurb.slice(0, 147).replace(/\s+\S*$/, '') + '\u2026';
  posts.push({ slug, date, name, label, blurb, mins: Math.max(1, Math.round(words / 230)) });
}
posts.sort((a, b) => b.date.localeCompare(a.date) || a.slug.localeCompare(b.slug));
const latest = posts.slice(0, N);
const fmt = d => { const [y, m, day] = d.split('-').map(Number); return `${MONTHS[m - 1]} ${day}, ${y}`; };

const arrow = '<svg width="13" height="13" viewBox="0 0 24 24" fill="none"><path d="M5 12h14M12 5l7 7-7 7" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"/></svg>';
const cards = latest.map(p => `          <a href="blog/${p.slug}" class="blog-latest-card reveal">
            <div class="blog-latest-meta"><span class="blog-latest-tag">${esc(p.label)}</span><span>${fmt(p.date)}</span><span>${p.mins} min read</span></div>
            <h3 class="blog-latest-title">${esc(p.name)}</h3>
            <p class="blog-latest-desc">${esc(p.blurb)}</p>
            <span class="blog-latest-more">Read article ${arrow}</span>
          </a>`).join('\n');

const SECTION = `<!-- BLOG-LATEST:START (generated by scripts/update-home-blog.js) -->
    <section id="latest-blog" class="blog-latest-section" aria-labelledby="blog-latest-heading">
      <div class="max-w-[1600px] mx-auto px-6 lg:px-10">

        <div class="text-center mb-12 reveal">
          <div class="section-eyebrow"><span class="dot"></span>From the Blog</div>
          <h2 id="blog-latest-heading" class="section-title">
            Local SEO Insights<span class="text-grad-accent"> for Home Service Businesses</span>
          </h2>
          <p class="section-subtitle">Practical guides on Google Business Profile, local search, reviews, and AI search, written for owners who want more calls and booked jobs.</p>
        </div>

        <div class="blog-latest-grid reveal-stagger">
${cards}
        </div>

        <div class="text-center mt-10 reveal">
          <a href="blog/" class="btn-chip">
            View All Articles
            ${arrow.replace('width="13" height="13"', 'width="14" height="14"')}
          </a>
        </div>
      </div>
    </section>
    <!-- BLOG-LATEST:END -->`;

const CSS = `    /* ---- Latest blog posts (home) ---- */
    .blog-latest-section{padding:100px 0;position:relative}
    .blog-latest-grid{display:grid;grid-template-columns:repeat(3,1fr);gap:20px}
    .blog-latest-card{display:flex;flex-direction:column;gap:12px;padding:26px 24px 22px;border-radius:20px;border:1px solid var(--border-default);background:var(--ink-raised);text-decoration:none;color:inherit;transition:transform 260ms var(--ease-silk,ease),border-color 260ms,box-shadow 260ms}
    .blog-latest-card:hover{transform:translateY(-5px);border-color:var(--border-accent);box-shadow:0 20px 48px rgba(15,15,35,0.10)}
    .blog-latest-meta{display:flex;flex-wrap:wrap;align-items:center;gap:8px 12px;font-family:'JetBrains Mono',monospace;font-size:10.5px;font-weight:600;letter-spacing:0.04em;color:var(--text-muted)}
    .blog-latest-tag{padding:3px 9px;border-radius:999px;background:rgba(91,95,239,0.12);color:var(--spectrum-core);text-transform:uppercase;letter-spacing:0.07em;font-weight:700}
    .blog-latest-title{font-family:'Sora',sans-serif;font-size:18px;font-weight:700;line-height:1.35;letter-spacing:-0.01em;color:var(--text-primary);margin:0}
    .blog-latest-desc{font-size:13.5px;line-height:1.65;color:var(--text-secondary);margin:0;flex:1}
    .blog-latest-more{display:inline-flex;align-items:center;gap:6px;font-size:13px;font-weight:600;color:var(--spectrum-core)}
    .blog-latest-card:hover .blog-latest-more svg{transform:translateX(3px)}
    .blog-latest-more svg{transition:transform 200ms}
    @media (max-width:1024px){.blog-latest-grid{grid-template-columns:repeat(2,1fr)}}
    @media (max-width:640px){.blog-latest-section{padding:72px 0}.blog-latest-grid{grid-template-columns:1fr}}
    :root[data-theme="dark"] .blog-latest-card:hover{box-shadow:0 20px 48px rgba(0,0,0,0.45)}`;

const F = ROOT + '/index.html';
let h = fs.readFileSync(F, 'utf8'); const cr = h.includes('\r\n'); h = h.replace(/\r\n/g, '\n');
if (h.includes('<!-- BLOG-LATEST:START')) {
  h = h.replace(/<!-- BLOG-LATEST:START[\s\S]*?<!-- BLOG-LATEST:END -->/, () => SECTION);
} else {
  const anchor = '    <section id="faqs"';
  if (h.split(anchor).length !== 2) throw new Error('faqs anchor');
  h = h.replace(anchor, () => SECTION + '\n\n' + anchor);
}
if (!h.includes('.blog-latest-grid{')) {
  const cssAnchor = '    :root[data-theme="dark"] .pf-card-top{background:rgba(255,255,255,0.015)}';
  if (!h.includes(cssAnchor)) throw new Error('css anchor');
  h = h.replace(cssAnchor, () => cssAnchor + '\n' + CSS);
}
fs.writeFileSync(F, cr ? h.replace(/\n/g, '\r\n') : h, 'utf8');
console.log('home blog section:', latest.map(p => `${p.date} ${p.slug}`).join('\n  '));
